/* Write src/fonts.js: the four Nunito faces in assets/fonts as base64
   strings, so they ship inside main.js. Obsidian's community store installs
   only main.js, manifest.json and styles.css, so a separate font file would
   never reach someone who installs the plugin. Generated and committed:
   run `npm run fonts` after changing a file in assets/fonts.
   Nunito is under the SIL Open Font License 1.1 (assets/fonts/OFL.txt). */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const WEIGHTS = [400, 500, 600, 700];
const lines = [
  "'use strict';",
  '/* GENERATED by scripts/build-fonts.mjs from assets/fonts — do not edit.',
  '   Nunito (SIL Open Font License 1.1, assets/fonts/OFL.txt), latin subset,',
  '   as base64 woff2 by weight. src/font-loader.js turns them into FontFaces. */',
  '',
  'const FONTS = {',
];
for (const w of WEIGHTS) {
  const b64 = readFileSync(join(root, `assets/fonts/nunito-latin-${w}-normal.woff2`)).toString('base64');
  lines.push(`  ${w}: '${b64}',`);
}
lines.push('};', '', 'module.exports = { FONTS };', '');
writeFileSync(join(root, 'src/fonts.js'), lines.join('\n'));
console.log('src/fonts.js written (' + WEIGHTS.join(', ') + ')');
